#!/usr/bin/env bash
set -euo pipefail
source_tree=$(realpath "${1:?usage: build-wpe.sh WEBKIT_SOURCE WORK_DIRECTORY}")
work=$(realpath -m "${2:?}")
cmake -S "$source_tree" -B "$work/build/wpe-memory" -G Ninja \
    -DPORT=WPE -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_C_COMPILER=clang-21 -DCMAKE_CXX_COMPILER=clang++-21 \
    -DCMAKE_C_COMPILER_LAUNCHER=ccache -DCMAKE_CXX_COMPILER_LAUNCHER=ccache \
    -DTRY_USE_LD_LLD=ON -DUSE_LD_LLD=ON \
    -DCMAKE_INSTALL_PREFIX="$work/sdk/wpe-memory" \
    -DENABLE_WPE_PLATFORM=ON -DENABLE_WPE_PLATFORM_HEADLESS=ON \
    -DENABLE_WPE_PLATFORM_DRM=OFF -DENABLE_WPE_PLATFORM_WAYLAND=OFF \
    -DENABLE_WPE_LEGACY_API=OFF -DENABLE_WPE_QT_API=OFF \
    -DENABLE_DOCUMENTATION=OFF -DENABLE_INTROSPECTION=OFF \
    -DENABLE_API_TESTS=OFF -DENABLE_LAYOUT_TESTS=OFF -DENABLE_MINIBROWSER=OFF \
    -DENABLE_VIDEO=OFF -DENABLE_WEB_AUDIO=OFF -DUSE_GSTREAMER=OFF \
    -DENABLE_SPEECH_SYNTHESIS=OFF -DENABLE_GAMEPAD=OFF \
    -DUSE_SYSPROF_CAPTURE=OFF -DUSE_SKIA_OPENTYPE_SVG=OFF -DUSE_LIBBACKTRACE=OFF
cmake --build "$work/build/wpe-memory" --parallel "${BRIMP_BUILD_JOBS:-24}"
cmake --install "$work/build/wpe-memory"
