//! Generate CLI documentation from the same Clap model as the executable, without native SDKs.
#[allow(dead_code)]
#[path = "../../../../crates/cli/src/args.rs"]
mod args;

use clap::CommandFactory;

fn render(mut command: clap::Command, name: String) {
    command = command.bin_name(&name).disable_help_subcommand(true);
    println!(
        "## `{name}`\n\n```text\n{}\n```\n",
        command.render_long_help()
    );
    for child in command.get_subcommands().cloned() {
        let child_name = format!("{name} {}", child.get_name());
        render(child, child_name);
    }
}

fn main() {
    println!(
        "---\ntitle: CLI reference\ndescription: Generated from the CLI's Clap command definitions.\n---\n"
    );
    println!("<!-- Generated by docs/tools/cli-reference. Do not edit. -->\n");
    println!(
        "This reference is generated from the executable's command definitions at every documentation build. For runnable examples, JSON actions/routes and output behavior, follow the [CLI tutorial](/examples/cli/) and [CLI workflows](/examples/cli-workflows/).\n"
    );
    render(args::Cli::command(), "brimp".into());
}
