import fs from 'node:fs';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const root=fileURLToPath(new URL('../../',import.meta.url));
const require=createRequire(new URL('../../docs/package.json',import.meta.url));
const coverage=require('yaml').parse(fs.readFileSync(`${root}/COVERAGE.yaml`,'utf8'));
const header=fs.readFileSync(`${root}/crates/lexbor/vendor/lexbor/source/lexbor/css/property/const.h`,'utf8');
const native=[...header.matchAll(/LXB_CSS_PROPERTY_([A-Z][A-Z_0-9]*)\s*=/g)]
  .map(match=>match[1].toLowerCase().replaceAll('_','-')).sort();
const nativeSet=new Set(native);
const cssName=name=>name.replace(/[A-Z]/g,c=>'-'+c.toLowerCase());
const fields=Object.values(coverage.fields).filter(f=>f.target==='CSSStyleDeclaration.instance');
if(fields.some(f=>!['present','absent'].includes(f.safari.presence)))throw Error('CSS inventory needs a measured Safari reference');
const placeholders=fields.filter(f=>f.safari.presence==='present'&&!nativeSet.has(cssName(f.name))).map(f=>f.name).sort();
const output=`// Generated by node scripts/coverage/css-properties.mjs.\n// Native names come from the vendored Lexbor property registry.\n// Placeholder names come from the measured Safari inventory in COVERAGE.yaml.\nconst __cssNativePropertyNames = new Set(${JSON.stringify(native,null,4)});\nconst __cssPlaceholderPropertyNames = ${JSON.stringify(placeholders,null,4)};\n`;
fs.writeFileSync(`${root}/crates/runtime/js/web_apis/css_property_names.js`,output);
console.log(JSON.stringify({nativeRegistry:native.length,placeholderFields:placeholders.length,safariAbsent:fields.filter(f=>f.safari.presence==='absent').length}));
